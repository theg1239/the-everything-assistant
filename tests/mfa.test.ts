import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import test, { mock } from 'node:test'
import { createGuardrails, generateSync } from 'otplib'
import {
  findBackupCode,
  generateBackupCodes,
  generateEmailCode,
  generateTOTPSecret,
  hashBackupCode,
  hashBackupCodes,
  isLegacyBackupCodeHash,
  matchTOTP,
  verifyTOTP,
} from '../lib/mfa'

const PERIOD = 30
// Mid-step, so ±30 s tolerance cannot straddle into a third step on either side.
const NOW_SECONDS = 1_800_000_015
// The classic 10-byte example secret ("Hello!\xDE\xAD\xBE\xEF"); 16 base32 chars is what
// otplib v12 generated by default, so already-enrolled users hold secrets of this size.
const LEGACY_10_BYTE_SECRET = 'JBSWY3DPEHPK3PXP'
const LEGACY_GUARDRAILS = createGuardrails({ MIN_SECRET_BYTES: 10 })

const BASE32 = /^[A-Z2-7]+$/

function codeAt(secret: string, epochSeconds: number): string {
  return generateSync({
    secret,
    epoch: epochSeconds,
    period: PERIOD,
    guardrails: LEGACY_GUARDRAILS,
  })
}

/** Runs `fn` with `Date.now()` pinned to `epochSeconds`. */
function atTime<T>(epochSeconds: number, fn: () => T): T {
  mock.timers.enable({ apis: ['Date'], now: epochSeconds * 1000 })
  try {
    return fn()
  } finally {
    mock.timers.reset()
  }
}

test('generateTOTPSecret returns a 20-byte base32 secret', () => {
  const secret = generateTOTPSecret()
  // 20 bytes = 160 bits = exactly 32 base32 characters, no padding.
  assert.equal(secret.length, 32)
  assert.match(secret, BASE32)
  assert.notEqual(generateTOTPSecret(), secret, 'secrets must be random')
})

test('verifyTOTP accepts the current code for a fresh secret', () => {
  const secret = generateTOTPSecret()
  const code = codeAt(secret, NOW_SECONDS)
  assert.match(code, /^\d{6}$/)
  assert.equal(
    atTime(NOW_SECONDS, () => verifyTOTP(code, secret)),
    true
  )
})

test('verifyTOTP accepts ±1 step of clock drift and rejects ±2 steps', () => {
  const secret = generateTOTPSecret()
  const cases: Array<[offsetSteps: number, expected: boolean]> = [
    [-2, false],
    [-1, true],
    [0, true],
    [1, true],
    [2, false],
  ]
  for (const [offsetSteps, expected] of cases) {
    const code = codeAt(secret, NOW_SECONDS + offsetSteps * PERIOD)
    // Guard against a (1 in 10^6) collision with the current code making the test flaky.
    if (!expected && code === codeAt(secret, NOW_SECONDS)) continue
    assert.equal(
      atTime(NOW_SECONDS, () => verifyTOTP(code, secret)),
      expected,
      `offset ${offsetSteps} step(s)`
    )
  }
})

test('verifyTOTP still verifies legacy 10-byte (16 base32 char) secrets', () => {
  assert.equal(LEGACY_10_BYTE_SECRET.length, 16)
  const code = codeAt(LEGACY_10_BYTE_SECRET, NOW_SECONDS)
  assert.equal(
    atTime(NOW_SECONDS, () => verifyTOTP(code, LEGACY_10_BYTE_SECRET)),
    true
  )
  const previous = codeAt(LEGACY_10_BYTE_SECRET, NOW_SECONDS - PERIOD)
  assert.equal(
    atTime(NOW_SECONDS, () => verifyTOTP(previous, LEGACY_10_BYTE_SECRET)),
    true
  )
})

test('verifyTOTP matches the RFC 6238 SHA-1 test vectors (independent of otplib generation)', () => {
  // Secret "12345678901234567890" (ASCII), base32-encoded. RFC 6238 Appendix B gives 8-digit
  // codes; the 6-digit code is the low 6 digits of the same truncated value.
  const rfcSecret = 'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ'
  const vectors: Array<[epochSeconds: number, code: string]> = [
    [59, '287082'],
    [1111111109, '081804'],
    [1234567890, '005924'],
    [2000000000, '279037'],
  ]
  for (const [epochSeconds, code] of vectors) {
    assert.equal(
      atTime(epochSeconds, () => verifyTOTP(code, rfcSecret)),
      true,
      `T=${epochSeconds}`
    )
  }
})

test('verifyTOTP rejects malformed tokens and secrets without throwing', () => {
  const secret = generateTOTPSecret()
  const malformed: unknown[] = [
    '',
    '12345',
    '1234567',
    'abcdef',
    '12 345',
    '-12345',
    '١٢٣٤٥٦',
    undefined,
    null,
    123456,
  ]
  atTime(NOW_SECONDS, () => {
    for (const token of malformed) {
      assert.doesNotThrow(() => verifyTOTP(token as string, secret))
      assert.equal(verifyTOTP(token as string, secret), false, `token ${JSON.stringify(token)}`)
    }
    const code = codeAt(secret, NOW_SECONDS)
    for (const badSecret of ['', 'not base32!', 'AAAA', '0189']) {
      assert.doesNotThrow(() => verifyTOTP(code, badSecret))
      assert.equal(verifyTOTP(code, badSecret), false, `secret ${JSON.stringify(badSecret)}`)
    }
  })
})

test('generateBackupCodes returns the requested number of 8-char uppercase hex codes', () => {
  assert.equal(generateBackupCodes().length, 10)
  const codes = generateBackupCodes(25)
  assert.equal(codes.length, 25)
  for (const code of codes) assert.match(code, /^[0-9A-F]{8}$/)
  assert.equal(new Set(codes).size, codes.length, 'codes should be unique')
})

const PEPPER = 'test-pepper-0123456789'

test('backup codes are stored as peppered HMACs and verify case-insensitively', () => {
  const codes = generateBackupCodes(5)
  const hashed = hashBackupCodes(codes, PEPPER)

  assert.equal(hashed.length, codes.length)
  for (const [index, hash] of hashed.entries()) {
    assert.match(hash, /^hmac1\$[0-9a-f]{64}$/)
    assert.equal(isLegacyBackupCodeHash(hash), false)
    assert.ok(!hash.includes(codes[index] ?? '?'), 'codes must not be stored in plain text')
    assert.notEqual(
      hash.slice('hmac1$'.length),
      createHash('sha256')
        .update(codes[index] ?? '')
        .digest('hex'),
      'peppered hash must differ from a bare SHA-256'
    )
  }

  for (const [index, code] of codes.entries()) {
    assert.deepEqual(findBackupCode(code, hashed, PEPPER), { index, legacy: false })
    // Users may type the code in lower case or with spaces/dashes.
    assert.deepEqual(findBackupCode(code.toLowerCase(), hashed, PEPPER), { index, legacy: false })
    assert.deepEqual(findBackupCode(`${code.slice(0, 4)}-${code.slice(4)} `, hashed, PEPPER), {
      index,
      legacy: false,
    })
  }

  assert.equal(findBackupCode('00000000', hashed, PEPPER), null)
  assert.equal(findBackupCode('', hashed, PEPPER), null)
  assert.equal(findBackupCode(codes[0] ?? '', [], PEPPER), null)
})

test('backup codes hashed with a different pepper do not verify', () => {
  const [code = ''] = generateBackupCodes(1)
  const hashed = hashBackupCodes([code], PEPPER)
  assert.equal(findBackupCode(code, hashed, 'another-pepper'), null)
  assert.notEqual(hashBackupCode(code, PEPPER), hashBackupCode(code, 'another-pepper'))
})

test('legacy unpeppered SHA-256 backup codes still verify and are flagged for retirement', () => {
  const codes = generateBackupCodes(3)
  const legacy = codes.map(code => createHash('sha256').update(code).digest('hex'))
  const mixed = [...legacy.slice(0, 2), ...hashBackupCodes([codes[2] ?? ''], PEPPER)]

  assert.equal(isLegacyBackupCodeHash(mixed[0] ?? ''), true)
  assert.deepEqual(findBackupCode(codes[0] ?? '', mixed, PEPPER), { index: 0, legacy: true })
  assert.deepEqual(findBackupCode((codes[1] ?? '').toLowerCase(), mixed, PEPPER), {
    index: 1,
    legacy: true,
  })
  assert.deepEqual(findBackupCode(codes[2] ?? '', mixed, PEPPER), { index: 2, legacy: false })
  // A legacy hash can't be matched by presenting the hash itself as the code.
  assert.equal(findBackupCode(legacy[0] ?? '', mixed, PEPPER), null)
})

test('matchTOTP reports the matched time step', () => {
  const secret = generateTOTPSecret()
  const currentStep = Math.floor(NOW_SECONDS / PERIOD)
  for (const offset of [-1, 0, 1]) {
    const code = codeAt(secret, NOW_SECONDS + offset * PERIOD)
    if (offset !== 0 && code === codeAt(secret, NOW_SECONDS)) continue
    assert.deepEqual(
      atTime(NOW_SECONDS, () => matchTOTP(code, secret)),
      { timeStep: currentStep + offset },
      `offset ${offset}`
    )
  }
  assert.equal(
    atTime(NOW_SECONDS, () => matchTOTP('000000', 'not base32!')),
    null
  )
})

test('generateEmailCode returns 6-digit codes from the CSPRNG', () => {
  const codes = Array.from({ length: 200 }, () => generateEmailCode())
  for (const code of codes) assert.match(code, /^[1-9]\d{5}$/)
  assert.ok(new Set(codes).size > 190, 'codes should not repeat much')
})
